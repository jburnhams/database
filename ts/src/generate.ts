/**
 * Migrations generated from the schema with drizzle-kit's API, in a folder the app commits:
 *
 *   migrations/0001_initial.sql          statements, separated by "--> statement-breakpoint"
 *   migrations/meta/0001_initial.json    drizzle-kit snapshot of the schema after it
 *
 * A new migration is the difference between the newest snapshot and the schema now; no difference, no file.
 * Review every file: like Alembic, a rename is seen as drop + add (data lost) and must be edited by hand.
 *
 * SQLite / D1: when drizzle-kit rebuilds a table (copy into __new_x, drop x, rename) it wraps it in
 * PRAGMA foreign_keys=OFF/ON, which does nothing inside a transaction and is ignored by D1. Those lines are removed;
 * migrateSqlite switches foreign keys off around the transaction itself (and checks them before COMMIT). On D1
 * a rebuild of a table that other rows reference cannot work (it fails and rolls back); `PRAGMA defer_foreign_keys`
 * is added at the top all the same, for the cases it does cover (rows inserted out of order within the batch).
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import type { Dialect } from "./config.js";

export const BREAKPOINT = "\n--> statement-breakpoint\n";

export interface MigrationFile { name: string; sql: string; statements: string[] }

export function listMigrations(dir: string): MigrationFile[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((f) => /^\d{4}_.+\.sql$/.test(f)).sort().map((f) => {
    const sql = readFileSync(join(dir, f), "utf8");
    return { name: f.replace(/\.sql$/, ""), sql, statements: splitStatements(sql) };
  });
}

export function splitStatements(sql: string): string[] {
  // Drop comment-only lines (the file header) so each statement starts with its SQL.
  return sql.split(/\n?--> statement-breakpoint\n?/)
    .map((s) => s.split("\n").filter((l) => !/^\s*--/.test(l)).join("\n").trim())
    .filter(Boolean);
}

async function api() {
  return await import("drizzle-kit/api");
}

function latestSnapshot(dir: string): any | undefined {
  const meta = join(dir, "meta");
  if (!existsSync(meta)) return undefined;
  const f = readdirSync(meta).filter((x) => /^\d{4}_.+\.json$/.test(x)).sort().pop();
  return f ? JSON.parse(readFileSync(join(meta, f), "utf8")) : undefined;
}

/** The SQL statements that would take the database from the newest snapshot to the schema (empty: in sync). */
export async function diff(dialect: Dialect, schema: Record<string, unknown>, dir: string): Promise<{ statements: string[]; snapshot: any }> {
  const k: any = await api();
  const prev = latestSnapshot(dir);
  if (dialect === "postgresql") {
    const empty = k.generateDrizzleJson({});
    const cur = k.generateDrizzleJson(schema, prev?.id);
    // The schema may already exist (omarchy-db new-app creates it, owned by the app role): never fail on it.
  const statements = (await k.generateMigration(prev ?? empty, cur)).map((s: string) => s.replace(/^CREATE SCHEMA "/, 'CREATE SCHEMA IF NOT EXISTS "'));
  return { statements, snapshot: cur };
  }
  const empty = await k.generateSQLiteDrizzleJson({});
  const cur = await k.generateSQLiteDrizzleJson(schema, prev?.id);
  return { statements: fixSqliteForeignKeys(await k.generateSQLiteMigration(prev ?? empty, cur)), snapshot: cur };
}

export function fixSqliteForeignKeys(statements: string[]): string[] {
  const out = statements.filter((s) => !/^PRAGMA foreign_keys\s*=\s*(OFF|ON);?$/i.test(s.trim()));
  return out.length !== statements.length ? ["PRAGMA defer_foreign_keys = on;", ...out] : out;
}

/** Write the next migration (and its snapshot) if the schema changed. Returns its path, or undefined. */
export async function generate(dialect: Dialect, schema: Record<string, unknown>, dir: string, message: string): Promise<string | undefined> {
  const { statements, snapshot } = await diff(dialect, schema, dir);
  if (!statements.length) return undefined;
  const n = listMigrations(dir).length + 1;
  const slug = message.toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/^_|_$/g, "").slice(0, 40) || "migration";
  const name = `${String(n).padStart(4, "0")}_${slug}`;
  mkdirSync(join(dir, "meta"), { recursive: true });
  const header = `-- ${message}\n-- Generated by omarchy-db from the schema; review before committing (renames show as drop + add).\n`;
  writeFileSync(join(dir, `${name}.sql`), header + statements.join(BREAKPOINT) + "\n");
  writeFileSync(join(dir, "meta", `${name}.json`), JSON.stringify(snapshot, null, 2) + "\n");
  return join(dir, `${name}.sql`);
}
